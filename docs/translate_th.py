# 主函数
def main():
    print("开始翻译泰语产品文件...")
    
    # 保持前4个产品不变
    result = products_th[:4]
    
    # 翻译后26个产品
    for i in range(4, len(products_en)):
        product_en = products_en[i]
        product_name = product_en['name']
        
        print(f"正在翻译产品 {i+1}/{len(products_en)}: {product_name}")
        
        # 如果有预定义的翻译，使用它
        if product_name in PRODUCT_TRANSLATIONS:
            translation = PRODUCT_TRANSLATIONS[product_name]
            product_th = {
                'name': product_name,
                'category': product_en['category'],
                'slug': product_en['slug'],
                'url': product_en['url'],
                'fullTitle': product_en['fullTitle'],
                'description': translation['description'],
                'advantages': translation['advantages'],
                'capabilities': translation['capabilities'],
                'applications': translation['applications'],
                'specs': translation['specs'],
                'specCount': product_en['specCount'],
                'hasChinese': product_en['hasChinese']
            }
        else:
            # 如果没有预定义翻译，保持英文原文（需要后续手动翻译）
            print(f"  警告: 产品 {product_name} 没有预定义翻译，保持英文原文")
            product_th = product_en.copy()
        
        result.append(product_th)
    
    # 保存结果
    with open('products_th_new.json', 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
    
    print(f"\n翻译完成！结果已保存到 products_th_new.json")
    print(f"总共处理了 {len(result)} 个产品")

if __name__ == '__main__':
    main()
